DROP DATABASE IF EXISTS `D&D`;
CREATE DATABASE `D&D`;
USE `D&D`;

CREATE TABLE razas (
 ID INT auto_increment PRIMARY KEY,
 nombre VARCHAR(60) NOT NULL UNIQUE,
 mundo_origen VARCHAR(80) DEFAULT 'Faerûn',
 tamaño ENUM('PEQUEÑO','MEDIANO','GRANDE') NOT NULL DEFAULT('MEDIANO'),
 velocidad_base INT UNSIGNED NOT NULL DEFAULT(30) CONSTRAINT chk_velocidad_base CHECK (velocidad_base BETWEEN 10 AND 60),
 vision_oscuridad BOOLEAN NOT NULL DEFAULT 0,
 idioma_principal VARCHAR(40) NOT NULL DEFAULT('Común'),
 bonif_fue INT NOT NULL DEFAULT(0),
 bonif_des INT NOT NULL DEFAULT(0),
 bonif_con INT NOT NULL DEFAULT(0),
 bonif_int INT NOT NULL DEFAULT(0),
 bonif_sab INT NOT NULL DEFAULT(0),
 bonif_car INT NOT NULL DEFAULT(0),
 resistencia_tipo ENUM('NINGUNA','FUEGO','FRIO','VENENO','ACIDO','RAYO','NECROTICO','RADIO') NOT NULL DEFAULT('NINGUNA'),
 rasgo_1 VARCHAR(60),
 rasgo_1_desc TEXT,
 rasgo_2 VARCHAR(60),
 rasgo_2_desc TEXT,
 rasgo_3 VARCHAR(60),
 rasgo_3_desc TEXT,
 jugable BOOLEAN NOT NULL DEFAULT 1,
 rareza ENUM('COMUN','POCO_COMUN','RARA','MUY_RARA','LEGENDARIA') NOT NULL DEFAULT('COMUN'),
 notas_master TEXT,
 fecha_creacion DATETIME NOT NULL DEFAULT(NOW()),
 fecha_update DATETIME NOT NULL DEFAULT(NOW())
);

CREATE TABLE clases (
 ID INT auto_increment PRIMARY KEY,
 nombre VARCHAR(60) NOT NULL UNIQUE,
 dado_vida ENUM('d6','d8','d10','d12') NOT NULL,
 atributo_principal ENUM('FUE','DES','CON','INT','SAB','CAR') NOT NULL,
 salvaciones SET('FUE','DES','CON','INT','SAB','CAR') NOT NULL,
 competencia_armas TEXT,
 competencia_armaduras TEXT,
 competencia_herram TEXT,
 competencia_habilidades SET('ACROBACIAS','ARCANO','ATLETISMO','ENGANAR','HISTORIA','INTERPRETACION',
 'INTIMIDACION','INVESTIGACION','JUEGO_DE_MANOS','MEDICINA','NATURALEZA','PERCEPCION','PERSUASION','RELIGION',
 'SIGILO','SUPERVIVENCIA','TRATO_CON_ANIMALES'),
 lanzador_conjuros BOOLEAN NOT NULL DEFAULT(FALSE),
 tipo_lanzamiento ENUM('NINGUNO','PREPARADO','CONOCIDO','PACTO') NOT NULL DEFAULT('NINGUNO'),
 recursos_principales VARCHAR(120),
 armadura_sin_bonif BOOLEAN NOT NULL DEFAULT(FALSE),
 notas_master TEXT,
 fecha_creacion DATETIME NOT NULL DEFAULT(NOW()),
 fecha_update DATETIME NOT NULL DEFAULT(NOW())
);

CREATE TABLE personajes (
 ID INT auto_increment PRIMARY KEY,
 nombre VARCHAR(80) NOT NULL,
 alias VARCHAR(80),
 genero ENUM('M','F','NB','OTRO') DEFAULT('OTRO'),
 edad INT UNSIGNED,
 altura_cm INT UNSIGNED,
 peso_kg INT UNSIGNED,
 raza INT NOT NULL,
 alineamiento ENUM('LB','NB','CB','LN','N','CN','LM','NM','CM') NOT NULL DEFAULT('N'),
 trasfondo VARCHAR(80),
 deidad VARCHAR(80),
 nivel_total INT UNSIGNED NOT NULL DEFAULT(1),
 exp_total INT UNSIGNED NOT NULL DEFAULT(0),
 inspiracion BOOLEAN NOT NULL DEFAULT(FALSE),
 fue TINYINT UNSIGNED NOT NULL DEFAULT(10) CHECK( fue BETWEEN 1 AND 30),
 des TINYINT UNSIGNED NOT NULL DEFAULT(10) CHECK( des BETWEEN 1 AND 30),
 con TINYINT UNSIGNED NOT NULL DEFAULT(10) CHECK( con BETWEEN 1 AND 30),
 inteli TINYINT UNSIGNED NOT NULL DEFAULT(10) CHECK( inteli BETWEEN 1 AND 30),
 sab TINYINT UNSIGNED NOT NULL DEFAULT(10) CHECK( sab BETWEEN 1 AND 30),
 car TINYINT UNSIGNED NOT NULL DEFAULT(10) CHECK( car BETWEEN 1 AND 30),
 ca_base TINYINT UNSIGNED NOT NULL DEFAULT(10),
 ca_total TINYINT UNSIGNED NOT NULL DEFAULT(10),
 iniciativa TINYINT NOT NULL DEFAULT(0),
 velocidad TINYINT UNSIGNED NOT NULL DEFAULT(30),
 pg_max SMALLINT UNSIGNED NOT NULL DEFAULT(8),
 pg_actual SMALLINT UNSIGNED NOT NULL DEFAULT(8),
 pg_temporales SMALLINT UNSIGNED NOT NULL DEFAULT(0),
 prof_salv_fue BOOLEAN NOT NULL DEFAULT(0),
 prof_salv_des BOOLEAN NOT NULL DEFAULT(0),
 prof_salv_con BOOLEAN NOT NULL DEFAULT(0),
 prof_salv_int BOOLEAN NOT NULL DEFAULT(0),
 prof_salv_sab BOOLEAN NOT NULL DEFAULT(0),
 prof_salv_car BOOLEAN NOT NULL DEFAULT(0),
 estado ENUM('ACTIVO','RETIRADO','MUERTO','NPC') NOT NULL DEFAULT('ACTIVO'),
 campaña VARCHAR(80),
 jugador VARCHAR(80),
 ultima_sesion DATE,
 oro INT UNSIGNED NOT NULL DEFAULT(0),
 plata INT UNSIGNED NOT NULL DEFAULT(0),
 cobre INT UNSIGNED NOT NULL DEFAULT(0),
 peso_cargado DECIMAL(6,2) NOT NULL DEFAULT(0.00),
 capacidad_carga DECIMAL(6,2) NOT NULL DEFAULT(0.00),
 personalidad TEXT,
 ideales TEXT,
 vinculos TEXT,
 defectos TEXT,
 rasgos_extra_json JSON ,
 fecha_creacion DATETIME NOT NULL DEFAULT(NOW()),
 fecha_update DATETIME NOT NULL DEFAULT(NOW()),
 CONSTRAINT fk_personaje_raza FOREIGN KEY (raza) REFERENCES razas(id) ON DELETE CASCADE,
 CONSTRAINT check_pg CHECK (pg_actual <= pg_max)
);

CREATE TABLE personaje_clase (
 ID INT auto_increment PRIMARY KEY,
 personaje INT NOT NULL,
 clase INT NOT NULL,
 nivel_clase INT UNSIGNED NOT NULL DEFAULT(1) CONSTRAINT chk_nivel_en_clase CHECK (nivel_clase BETWEEN 1 AND 20),
 subclase VARCHAR(80),
 dado_vida_restante TINYINT UNSIGNED NOT NULL DEFAULT(0),
 estilo_combate VARCHAR(80),
 notas_master TEXT,
 fecha_creacion DATETIME NOT NULL DEFAULT(NOW()),
 fecha_update DATETIME NOT NULL DEFAULT(NOW()),
 CONSTRAINT fk_pc_personaje FOREIGN KEY (personaje) REFERENCES personajes(id) ON DELETE CASCADE,
 CONSTRAINT fk_pc_clase FOREIGN KEY (clase) REFERENCES clases(id) ON DELETE CASCADE, 
 CONSTRAINT uq_personaje_clase UNIQUE (personaje, clase)
);

CREATE TABLE hechizos (
 ID INT auto_increment PRIMARY KEY,
 nombre VARCHAR(90) NOT NULL UNIQUE,
 nivel TINYINT UNSIGNED NOT NULL DEFAULT(0) CONSTRAINT chk_nivel_hechizo CHECK (nivel BETWEEN 0 AND 9),
 escuela ENUM('ABJURACION','CONJURACION','DIVINACION','ENCANTAMIENTO','EVOCACION','ILUSION','NECROMANCIA','TRANSMUTACION') NOT NULL,
 ritual BOOLEAN NOT NULL DEFAULT(FALSE),
 tiempo_lanzamiento VARCHAR(40) NOT NULL DEFAULT('1 acción'),
 alcance VARCHAR(40) NOT NULL DEFAULT('Personal'),
 componentes SET('V','S','M') NOT NULL DEFAULT('V'),
 material VARCHAR(140),
 duracion VARCHAR(60) NOT NULL DEFAULT('Instantánea'),
 concentracion BOOLEAN NOT NULL DEFAULT(FALSE),
 tirada_salvacion ENUM('NINGUNA','FUE','DES','CON','INT','SAB','CAR') NOT NULL DEFAULT('NINGUNA'),
 tipo_daño ENUM('NINGUNO','FUEGO','FRIO','VENENO','ACIDO','RAYO','TRUENO','NECROTICO','PSIQUICO','RADIO','FUERZA','CORTANTE','CONTUNDENTE','PERFORANTE') NOT NULL DEFAULT('NINGUNO'),
 descripcion TEXT NOT NULL,
 nivel_superior_desc TEXT,
 fuente VARCHAR(80) NOT NULL DEFAULT('PHB'),
 rareza ENUM('COMUN','POCO_COMUN','RARA','MUY_RARA','LEGENDARIA') NOT NULL DEFAULT('COMUN'),
 permitido_pj BOOLEAN NOT NULL DEFAULT(TRUE),
 fecha_creacion DATETIME NOT NULL DEFAULT(NOW()),
 fecha_update DATETIME NOT NULL DEFAULT(NOW())
);

CREATE TABLE objetos (
 id INT auto_increment PRIMARY KEY,
 nombre VARCHAR(90) NOT NULL UNIQUE,
 tipo ENUM('ARMA','ARMADURA','CONSUMIBLE','HERRAMIENTA','TESORO','ARTEFACTO','MISC') NOT NULL DEFAULT('MISC'),
 rareza ENUM('COMUN','POCO_COMUN','RARA','MUY_RARA','LEGENDARIA') NOT NULL DEFAULT('COMUN'),
 requiere_sintonia BOOLEAN NOT NULL DEFAULT(FALSE),
 peso DECIMAL(6,2) NOT NULL DEFAULT(0.00),
 valor_oro DECIMAL(10,2) NOT NULL DEFAULT(0.00),
 tipo_daño ENUM('NINGUNO','CORTANTE','CONTUNDENTE','PERFORANTE','FUEGO','FRIO','VENENO','ACIDO','RAYO','TRUENO','NECROTICO','PSIQUICO','RADIO','FUERZA') NOT NULL DEFAULT('NINGUNO'),
 dado_daño VARCHAR(10),
 propiedad_armas SET('LIGERA','PESADA','A_DISTANCIA','FINA','DOS_MANOS','VERSATIL','RECARGA','ALCANCE','ARROJADIZA','MUNICION'),
 ca_bonus TINYINT NOT NULL DEFAULT(0),
 tipo_armadura ENUM('NINGUNA','LIGERA','MEDIA','PESADA','ESCUDO') NOT NULL DEFAULT('NINGUNA'),
 req_fuerza TINYINT UNSIGNED,
 sigilo_desventaja BOOLEAN NOT NULL DEFAULT(FALSE),
 descripcion TEXT,
 efectos_json JSON,
 consumible_cargas SMALLINT UNSIGNED NOT NULL DEFAULT(0),
 permitido_pj BOOLEAN NOT NULL DEFAULT(TRUE),
 fuente VARCHAR(80) NOT NULL DEFAULT('PHB'),
 fecha_creacion DATETIME NOT NULL DEFAULT(NOW()),
 fecha_update DATETIME NOT NULL DEFAULT(NOW())
);

CREATE TABLE inventario (
 id INT auto_increment PRIMARY KEY,
 personaje INT NOT NULL,
 objeto INT NOT NULL,
 cantidad SMALLINT UNSIGNED NOT NULL DEFAULT(1) CONSTRAINT chk_cantidad CHECK (cantidad >= 1),
 equipado BOOLEAN NOT NULL DEFAULT(FALSE),
 ranura_equipo ENUM('CABEZA','TORSO','MANO_DER','MANO_IZQ','PIES','CINTURON','ANILLO','COLGANTE','MOCHILA','OTRO') NOT NULL DEFAULT('MOCHILA'),
 estado_objeto ENUM('NUEVO','USADO','DANADO','ROTO','MALDITO') NOT NULL DEFAULT('USADO'),
 cargas_actuales SMALLINT UNSIGNED NOT NULL DEFAULT(0),
 personalizacion VARCHAR(120),
 notas TEXT,
 obtenido_en DATE,
 fecha_creacion DATETIME NOT NULL DEFAULT(NOW()),
 CONSTRAINT fk_inv_personaje FOREIGN KEY (personaje) REFERENCES personajes(id) ON DELETE CASCADE,
 CONSTRAINT fk_inv_objeto FOREIGN KEY (objeto) REFERENCES objetos(id) ON DELETE CASCADE
);

