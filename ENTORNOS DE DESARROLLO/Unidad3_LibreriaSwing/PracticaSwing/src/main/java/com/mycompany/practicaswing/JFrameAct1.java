    /**
     * Maneja el evento de clic en el botón ENTER para validar credenciales.
     * 
     * Valida que:
     * 1. Los campos no estén vacíos
     * 2. El usuario coincida con "Pepe"
     * 3. La contraseña coincida con "12345"
     * 
     * Actualiza el label IndicadorCampos con el resultado de la validación.
     * 
     * @param evt Evento de acción del botón
     */
    private void BotonEnterActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BotonEnterActionPerformed
        String usuario = CampoUsuario.getText();
        String contrasena = CampoContrasena.getText();
        String usuarioPepe = "Pepe";
        String contrasenaPepe = "12345";
        String indicadorcampos = IndicadorCampos.getText();

        if (usuario.equals(usuarioPepe) && contrasena.equals(contrasenaPepe)) {
            indicadorcampos = "Usuario y contraseña correctos";
        } else if (usuario.isEmpty() || contrasena.isEmpty()) {
            indicadorcampos = "Debe rellenar ambos campos";
        } else {
            indicadorcampos = "Usuario o contraseña incorrectos";
        }
        IndicadorCampos.setText(indicadorcampos);

    }//GEN-LAST:event_BotonEnterActionPerformed

